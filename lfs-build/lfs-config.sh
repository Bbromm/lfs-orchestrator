#!/bin/bash
###############################################################################
# lfs-config.sh — Конфигурация сборки LFS 13.1-systemd
# Отредактируйте ПЕРЕД запуском build-lfs.sh!
###############################################################################

#------------------------------------------------------------------------------
# Основные пути
#------------------------------------------------------------------------------
export LFS="/mnt/lfs"                     # Точка монтирования LFS
export LFS_BUILD_DIR="/root/lfs-build"    # Каталог со скриптами
export LFS_TGT="$(uname -m)-lfs-linux-gnu"  # Определяется автоматически
export LFS_VERSION="13.1-systemd"

#------------------------------------------------------------------------------
# Разметка диска (ОПАСНО! Все данные на диске будут уничтожены)
#------------------------------------------------------------------------------
# Установите AUTO_PARTITION=yes, чтобы автоматически разметить диск
# или AUTO_PARTITION=no, чтобы разметить вручную (рекомендуется для первого раза)
export AUTO_PARTITION="no"

export DISK="/dev/sda"                    # Целевой диск
export PART_LFS="${DISK}5"                # Раздел LFS (root)
export PART_BOOT="${DISK}3"               # Раздел /boot (опционально)
export PART_SWAP="${DISK}4"               # Раздел swap
export PART_EFI="${DISK}1"                # Раздел EFI System (для UEFI)
export PART_BIOS="${DISK}2"               # Раздел BIOS Boot (для BIOS+GPT)

# Файловые системы
export FS_LFS="ext4"
export FS_BOOT="ext2"
export FS_EFI="vfat"

# Использовать загрузку через UEFI?
export USE_UEFI="yes"

#------------------------------------------------------------------------------
# Сеть и локаль
#------------------------------------------------------------------------------
export HOSTNAME="lfs"
export TIMEZONE="Europe/Moscow"
export LOCALE="ru_RU.UTF-8"
export KEYMAP="ru"
export CONSOLE_FONT="Lat2-Terminus16"
export USE_DHCP="yes"
export STATIC_IP="192.168.1.100"
export GATEWAY="192.168.1.1"
export DNS_PRIMARY="8.8.8.8"
export DNS_SECONDARY="8.8.4.4"

#------------------------------------------------------------------------------
# Ядро Linux
#------------------------------------------------------------------------------
# KERNEL_CONFIG_METHOD:
#   "defconfig"  — базовый defconfig + обязательные опции из книги (автоматически)
#   "menuconfig" — интерактивная настройка (по умолчанию, рекомендуется)
#   "custom"     — использовать готовый файл kernel/lfs-defconfig
export KERNEL_CONFIG_METHOD="menuconfig"
export KERNEL_JOBS="$(nproc)"

#------------------------------------------------------------------------------
# Поведение скрипта
#------------------------------------------------------------------------------
# Запускать тесты в Главе 8 (0=нет, 1=да)
export RUN_TESTS="0"

# Останавливаться при ошибке (1=да, рекомендуется)
export STOP_ON_ERROR="1"

# Пропускать уже выполненные фазы (1=да, использует state/*.done)
export RESUME_MODE="yes"

# Автоматически подтверждать опасные операции (1=да, для CI)
export FORCE_YES="no"